export const MAP_VIEWBOX = (() => {
  const [x0, y0] = projectLonLat(-128, 72)
  const [x1, y1] = projectLonLat(160, -42)
  return `${x0.toFixed(0)} ${y0.toFixed(0)} ${(x1 - x0).toFixed(0)} ${(y1 - y0).toFixed(0)}`
})()

