/**
 * Very rough continent outlines as [longitude, latitude] pairs.
 * Deliberately stylised — they are rendered as a dot-matrix, not a precise map.
 */
type Ring = [number, number][]

export const MAP_W = 1000
const LAT_TOP = 75
const LAT_BOTTOM = -50
export const MAP_H = Math.round(((LAT_TOP - LAT_BOTTOM) / 360) * MAP_W)

export function projectLonLat(lon: number, lat: number): [number, number] {
  return [((lon + 180) / 360) * MAP_W, ((LAT_TOP - lat) / 360) * MAP_W]
}

